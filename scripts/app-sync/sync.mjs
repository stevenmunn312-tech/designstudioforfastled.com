// Sync the site's patterns and preview engine from Design Studio for FastLED.
//
//   node scripts/app-sync/sync.mjs [path-to-app-repo]
//
// The app repo defaults to $DESIGN_STUDIO_APP, else a `Design-Studio-for-FastLED`
// checkout beside this repo. It needs its own `npm install`: the build uses the
// app's esbuild and jsdom, and resolves the app's imports from its node_modules.
//
// Writes (all generated — re-run this script rather than editing them):
//   src/lib/app-engine/engine.js          the app's evaluator and LED renderers
//   src/lib/built-in-patterns.json        catalogue of the app's built-in patterns
//   public/pattern-files/built-in/*.json  one downloadable pattern file each
//
// Re-run after the app changes a node, the preview renderer, or its library,
// so the site keeps rendering exactly what the app renders.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, "../..");

function findAppRoot() {
  const candidates = [
    process.argv[2],
    process.env.DESIGN_STUDIO_APP,
    resolve(siteRoot, "../Design-Studio-for-FastLED"),
    // A git worktree lives at <repo>/.claude/worktrees/<name>, so the sibling
    // of the main checkout is three levels further up.
    resolve(siteRoot, "../../../../Design-Studio-for-FastLED"),
  ].filter(Boolean);
  const found = candidates.map((path) => resolve(path)).find((path) => existsSync(join(path, "src/state/graphEvaluator.ts")));
  if (!found) {
    throw new Error(`Design Studio for FastLED checkout not found. Tried:\n  ${candidates.join("\n  ")}\nPass its path as the first argument.`);
  }
  return found;
}

const appRoot = findAppRoot();
const appRequire = createRequire(join(appRoot, "package.json"));
const { build } = appRequire("esbuild");
const { JSDOM } = appRequire("jsdom");

const shared = {
  bundle: true,
  format: "esm",
  logLevel: "warning",
  alias: { "@app": join(appRoot, "src") },
  // App modules import from its own node_modules (zustand, poline, …).
  nodePaths: [join(appRoot, "node_modules")],
  loader: { ".webp": "dataurl", ".png": "dataurl", ".jpg": "dataurl", ".svg": "dataurl", ".css": "empty" },
  define: { "import.meta.env.DEV": "false", "import.meta.env.VITEST": "false", "import.meta.env": "{}" },
};

// 1. The engine bundle the site's preview components load in the browser.
const graphStoreStub = join(here, "graph-store-stub.ts");
const engineOut = join(siteRoot, "src/lib/app-engine/engine.js");
await build({
  ...shared,
  entryPoints: [join(here, "engine-entry.ts")],
  outfile: engineOut,
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  banner: {
    js: [
      "// @ts-nocheck",
      "/* eslint-disable */",
      "// GENERATED by scripts/app-sync/sync.mjs from Design Studio for FastLED — do not edit.",
      "// AnimARTrix (bundled below) is CC-BY-NC-SA-4.0; see src/lib/evaluator/animartrix/LICENSE.md.",
    ].join("\n"),
  },
  plugins: [{
    name: "graph-store-stub",
    setup(b) {
      b.onResolve({ filter: /\/graphStore$/ }, (args) =>
        args.importer.startsWith(appRoot) || args.importer.startsWith(join(appRoot, "src")) ? { path: graphStoreStub } : undefined);
    },
  }],
});
// The Code node's sandbox is a module worker the app spawns with
// `new Worker(new URL("./codeSandbox.worker.ts", import.meta.url))`. esbuild
// keeps that expression verbatim, so build the worker beside the engine and
// point the URL at it; Next bundles it from there.
const workerSource = "./codeSandbox.worker.ts";
const workerName = "codeSandbox.worker.js";
await build({
  ...shared,
  entryPoints: [join(appRoot, "src/state/codeSandbox.worker.ts")],
  outfile: join(siteRoot, "src/lib/app-engine", workerName),
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  banner: { js: "// @ts-nocheck\n/* eslint-disable */\n// GENERATED by scripts/app-sync/sync.mjs from Design Studio for FastLED — do not edit." },
});
const engineCode = readFileSync(engineOut, "utf8");
if (!engineCode.includes(`"${workerSource}"`)) {
  throw new Error(`Engine no longer spawns ${workerSource}; update sync.mjs's worker step.`);
}
writeFileSync(engineOut, engineCode.replaceAll(`"${workerSource}"`, `"./${workerName}"`));
console.log(`Engine → ${engineOut}`);

// 2. The catalogue and pattern files. Run in Node against an empty in-memory
// origin, the way the app's own scripts/run-ts.mjs does: app stores read
// browser storage when they load.
const tmpDir = join(siteRoot, "node_modules/.cache/app-sync");
mkdirSync(tmpDir, { recursive: true });
const dumpOut = join(tmpDir, "dump-patterns.mjs");
await build({
  ...shared,
  entryPoints: [join(here, "dump-patterns.ts")],
  outfile: dumpOut,
  platform: "node",
  // pattern-runner.ts lazy-loads the browser bundle; the dump hands it the
  // app's modules from source instead, so never pull a second copy in.
  external: ["./engine.js"],
});

const dom = new JSDOM("", { url: "http://localhost" });
Object.assign(globalThis, {
  window: dom.window,
  document: dom.window.document,
  localStorage: dom.window.localStorage,
  sessionStorage: dom.window.sessionStorage,
});
process.argv = [
  process.argv[0],
  dumpOut,
  join(siteRoot, "src/lib/built-in-patterns.json"),
  join(siteRoot, "public/pattern-files/built-in"),
];
try {
  await import(pathToFileURL(dumpOut).href);
} finally {
  dom.window.close();
  rmSync(dumpOut, { force: true });
}
