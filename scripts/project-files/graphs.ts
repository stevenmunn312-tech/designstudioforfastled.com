/**
 * The graph inside each example project file, keyed by the project's slug in
 * src/lib/projects.ts. build.mjs turns these into project files with the app's
 * own node library, so only what differs from a node's defaults is written
 * here. Pins are left out on purpose: the build assigns every part a free pin
 * on the project's board, exactly as the app does when you add a part.
 *
 * A wire is "node.output -> node.input". A property value "$id" names another
 * node, as an Audio node's source does. `col` and `row` place a node on the
 * canvas in columns of 260 px and rows of 180 px.
 */

export interface NodeSpec {
  id: string;
  type: string;
  col: number;
  row?: number;
  /** Canvas title, when the node's own name would not say what it is for. */
  label?: string;
  properties?: Record<string, unknown>;
}

export interface ProjectGraph {
  /** Board profile id; the ESP32-S3 DevKitC-1 when left out. */
  board?: string;
  /** The Board's global brightness, 0–255. */
  brightness?: number;
  /** LED power cap in mA, for a battery build; full-white draw when left out. */
  powerCapMa?: number;
  /** Fill the Pattern Collection with audio-reactive built-ins for this form. */
  showPatterns?: "string" | "matrix";
  nodes: NodeSpec[];
  wires: string[];
}

const note = (id: string, col: number, row: number, text: string): NodeSpec =>
  ({ id, type: "Comment", col, row, properties: { text, color: "#74d7ff" } });

/** A microphone, read the way the app's starters read one: through Audio. */
const microphone = (col: number, row: number): NodeSpec[] => [
  { id: "mic", type: "MicInput", col, row },
  { id: "audio", type: "Audio", col, row, properties: { sourceId: "$mic" } },
];

/** A DS3231 keeps the time through power cuts, which every timed build needs. */
const realTimeClock = (col: number, row: number): NodeSpec[] => [
  { id: "clock", type: "RTCInput", col, row, properties: { timeSource: "DS3231" } },
  { id: "rtc", type: "RtcModule", col, row: row + 1 },
];

/**
 * One octave, C4 to B4, over a 24-LED strip: two LEDs above each key. A MIDI
 * node watches one note, so each key gets its own node, drawing a green Line
 * over its two LEDs while held. A Crossfade Cycle of blue Lines plays the
 * lesson, a key at a time, and the played keys light over it.
 */
function pianoTeacher(): ProjectGraph {
  const names = ["C", "C♯", "D", "D♯", "E", "F", "F♯", "G", "G♯", "A", "A♯", "B"];
  const keyLine = (key: number, rgb: [number, number, number]) => ({
    units: "pixels", x1: key * 2, y1: 0, x2: key * 2 + 1, y2: 0, thickness: 1, r: rgb[0], g: rgb[1], b: rgb[2],
  });
  const nodes: NodeSpec[] = [
    { id: "midiPort", type: "MidiInterface", col: 0, row: -1 },
    note("guide", 1, -1, "PIANO TEACHER\nBlue shows the next note of the lesson; keys you play light green.\nThe lesson is C E G E, a note every two seconds.\nMove the four blue Lines to teach a different phrase."),
  ];
  const wires: string[] = [];
  names.forEach((name, key) => {
    nodes.push(
      { id: `key${key}`, type: "MidiInput", col: 0, row: key, label: `${name}4`, properties: { midiSource: "DIN (UART)", note: 60 + key } },
      { id: `lit${key}`, type: "Math", col: 1, row: key, label: `${name}4 green`, properties: { mathOp: "multiply", b: 255 } },
      { id: `draw${key}`, type: "Line", col: 2 + key * 0.25, row: key, label: `${name}4 key`, properties: keyLine(key, [0, 0, 0]) },
    );
    wires.push(`key${key}.gate -> lit${key}.a`, `lit${key}.result -> draw${key}.g`);
    if (key > 0) wires.push(`draw${key - 1}.frame -> draw${key}.base`);
  });
  const lesson = [0, 4, 7, 4];
  lesson.forEach((key, step) => {
    nodes.push({ id: `step${step}`, type: "Line", col: 3, row: 13 + step, label: `Lesson note ${step + 1}: ${names[key]}4`, properties: keyLine(key, [0, 60, 255]) });
    wires.push(`step${step}.frame -> lesson.p${step}`);
  });
  nodes.push(
    { id: "lesson", type: "Sequencer", col: 4, row: 14, properties: { interval: 2, fade: 0.2 } },
    { id: "mix", type: "Blend", col: 5, row: 12, properties: { blendMode: "lighten", amount: 1 } },
    { id: "out", type: "MatrixOutput", col: 6, row: 12, properties: { form: "strip", ledCount: 24 } },
  );
  wires.push("lesson.frame -> mix.a", "draw11.frame -> mix.b", "mix.frame -> out.frame");
  return { nodes, wires };
}

